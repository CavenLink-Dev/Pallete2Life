/* Simple RGB Euclidean distance between two #RRGGBB values. */
export function hexDistance(a: string, b: string): number {
  const [ra, ga, ba] = hexToRgb(a)
  const [rb, gb, bb] = hexToRgb(b)
  return Math.sqrt((ra - rb) ** 2 + (ga - gb) ** 2 + (ba - bb) ** 2)
}

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace("#", "")
  const v = h.length === 3 ? h.split("").map((c) => c + c).join("") : h
  const n = parseInt(v || "000000", 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

/* Recency-aware curated pick that respects locked positions.
 * Returns the chosen palette (5 hex values) or null if no curated
 * palette is a reasonable match for the locked colours. */
export function pickCuratedPalette(
  locks: Array<{ idx: number; hex: string }>,
  recent: readonly number[],
): { palette: readonly string[]; index: number } | null {
  const RECENT_WINDOW = 20                    // how many recent picks to avoid
  const MAX_DIST_PER_LOCK = 80                // ~soft threshold in RGB distance
  const avoid = new Set(recent.slice(0, RECENT_WINDOW))

  let candidates = CURATED_PALETTES.map((p, index) => ({ p, index })).filter((c) => !avoid.has(c.index))
  if (candidates.length === 0) candidates = CURATED_PALETTES.map((p, index) => ({ p, index }))

  if (locks.length === 0) {
    const pick = candidates[Math.floor(Math.random() * candidates.length)]
    return { palette: pick.p, index: pick.index }
  }

  // Filter locks to positions the curated palettes actually cover
  const relevant = locks.filter((l) => l.idx >= 0 && l.idx < 5)
  if (relevant.length === 0) {
    const pick = candidates[Math.floor(Math.random() * candidates.length)]
    return { palette: pick.p, index: pick.index }
  }

  // Score by total RGB distance at all locked positions; take the best.
  const scored = candidates.map((c) => ({
    ...c,
    dist: relevant.reduce((sum, lock) => sum + hexDistance(c.p[lock.idx], lock.hex), 0),
  }))
  scored.sort((a, b) => a.dist - b.dist)
  const best = scored[0]
  if (best.dist > MAX_DIST_PER_LOCK * relevant.length) return null
  return { palette: best.p, index: best.index }
}
